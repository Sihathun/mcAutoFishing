"""
Developer tool: build the app icon from the logo.

    python tools/make_icon.py

Reads  assets/logo_source.png   (the full logo, with the "Auto Fishing Tool" text)
Writes assets/AutoFishing.ico   (the .exe icon; 16-256 px)
       assets/icon_preview.png  (all icon sizes on light and dark backgrounds, for eyeballing)
       appicon.py               (the same icon embedded as base64, used for the window/taskbar icon)

The text is dropped for the icon: it is unreadable at 16-48 px, so only the rod is used. The rod is the
largest connected shape in the logo; the lettering is a set of small separate shapes.
"""
import base64
import io
import sys
import textwrap
from pathlib import Path

import cv2
import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "assets" / "logo_source.png"
ICO = ROOT / "assets" / "AutoFishing.ico"
PREVIEW = ROOT / "assets" / "icon_preview.png"
APPICON_PY = ROOT / "appicon.py"

ICO_SIZES = (16, 24, 32, 48, 64, 128, 256)
EMBED_SIZE = 256
MARGIN = 0.07   # empty border around the rod, as a fraction of its size


def extract_rod(logo: Image.Image) -> Image.Image:
    """The logo with everything but the largest connected shape (the rod) removed, cropped to it."""
    rgba = np.array(logo.convert("RGBA"))
    count, labels, stats, _ = cv2.connectedComponentsWithStats((rgba[..., 3] > 40).astype(np.uint8), connectivity=8)
    if count < 2:
        sys.exit("The logo has no visible shapes.")
    rod = 1 + int(np.argmax(stats[1:, cv2.CC_STAT_AREA]))
    keep = labels == rod
    # Anti-aliased fringe pixels (alpha 1..40) sit right next to the rod: keep those within 2 px of it.
    near = cv2.dilate(keep.astype(np.uint8), np.ones((5, 5), np.uint8)).astype(bool)
    rgba[~near, 3] = 0
    x, y, w, h = (int(stats[rod, c]) for c in (cv2.CC_STAT_LEFT, cv2.CC_STAT_TOP,
                                                cv2.CC_STAT_WIDTH, cv2.CC_STAT_HEIGHT))
    pad = 2
    y0, x0 = max(y - pad, 0), max(x - pad, 0)
    return Image.fromarray(rgba[y0:y + h + pad, x0:x + w + pad], "RGBA")


def square_canvas(rod: Image.Image) -> Image.Image:
    """Center the rod on a transparent square with a small margin."""
    side = int(round(max(rod.size) * (1 + 2 * MARGIN)))
    canvas = Image.new("RGBA", (side, side), (0, 0, 0, 0))
    canvas.alpha_composite(rod, ((side - rod.width) // 2, (side - rod.height) // 2))
    return canvas


def render(square: Image.Image, size: int) -> Image.Image:
    # Pillow premultiplies alpha when resizing RGBA, so there are no dark fringes around the edges.
    return square.resize((size, size), Image.Resampling.LANCZOS)


def preview(images: dict) -> Image.Image:
    """Every size on a light and a dark background, plus an enlarged copy, to judge legibility."""
    pad = 12
    width = sum(s for s in images) + pad * (len(images) + 1)
    sheet = Image.new("RGBA", (width, 2 * (max(images) + 2 * pad)), (0, 0, 0, 0))
    for row, bg in enumerate(((243, 244, 246, 255), (32, 32, 32, 255))):
        top = row * (max(images) + 2 * pad)
        sheet.paste(Image.new("RGBA", (width, max(images) + 2 * pad), bg), (0, top))
        x = pad
        for size, img in images.items():
            sheet.alpha_composite(img, (x, top + pad + (max(images) - size) // 2))
            x += size + pad
    return sheet


def write_appicon(png_bytes: bytes) -> None:
    b64 = base64.b64encode(png_bytes).decode("ascii")
    body = "\n".join(f'    "{line}"' for line in textwrap.wrap(b64, 96))
    APPICON_PY.write_text(
        '"""The app icon (the fishing rod), embedded so it works from source and inside the .exe.\n\n'
        "Generated by tools/make_icon.py from assets/logo_source.png. Do not edit by hand.\n"
        '"""\n'
        "ICON_PNG_B64 = (\n" + body + "\n)\n",
        encoding="utf-8",
    )


def main() -> None:
    if not SOURCE.exists():
        sys.exit(f"Missing {SOURCE}")
    square = square_canvas(extract_rod(Image.open(SOURCE)))
    images = {s: render(square, s) for s in ICO_SIZES}

    # Pillow's ICO writer picks sizes from the largest image; hand it each size so none is re-resampled.
    largest = images[max(ICO_SIZES)]
    largest.save(ICO, format="ICO", sizes=[(s, s) for s in ICO_SIZES],
                 append_images=[images[s] for s in ICO_SIZES if s != max(ICO_SIZES)])
    preview(images).save(PREVIEW)

    buf = io.BytesIO()
    images[EMBED_SIZE].save(buf, format="PNG", optimize=True)
    write_appicon(buf.getvalue())
    print(f"wrote {ICO.name} ({ICO.stat().st_size} bytes), {PREVIEW.name}, "
          f"{APPICON_PY.name} (embedded PNG {len(buf.getvalue())} bytes)")


if __name__ == "__main__":
    main()
